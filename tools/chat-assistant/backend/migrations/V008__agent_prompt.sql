-- V008: Agent Prompt version management table
-- Supports versioned prompt templates, A/B testing, and performance tracking.

CREATE TABLE IF NOT EXISTS agent_prompt (
    id              BIGINT AUTO_INCREMENT PRIMARY KEY,
    prompt_key      VARCHAR(64)    NOT NULL COMMENT 'Prompt identifier, e.g. planner, tool_turn, reflection',
    version         INT            NOT NULL DEFAULT 1 COMMENT 'Monotonic version number per prompt_key',
    template        TEXT           NOT NULL COMMENT 'System prompt template — the full prompt text',
    temperature     DOUBLE         NOT NULL DEFAULT 0.1 COMMENT 'LLM temperature override for this prompt version',
    is_active       TINYINT        NOT NULL DEFAULT 1 COMMENT '0=disabled, 1=active (eligible for A/B)',
    traffic_pct     INT            NOT NULL DEFAULT 100 COMMENT 'Traffic percentage for A/B (0-100)',
    performance_score DOUBLE       NULL COMMENT 'Average user rating (1-5), updated by feedback loop',
    description     VARCHAR(512)   NULL COMMENT 'Human-readable changelog for this version',
    create_time     DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_key_active (prompt_key, is_active),
    UNIQUE KEY uk_key_version (prompt_key, version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Agent Prompt version registry';

-- Seed data is managed through the PromptRegistry fallback in prompts.py.
-- To add DB-managed prompt versions, INSERT directly or use an admin API.
-- The built-in fallback templates are kept in sync with prompts.py:_FALLBACK_PROMPTS.

